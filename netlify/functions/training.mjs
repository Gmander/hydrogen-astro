async function readJSON(request) {
  if (!request.headers.get("content-type")?.startsWith("application/json")) throw new AppError(415, "json_required", "JSON is required.");
  const reader = request.body?.getReader();
  if (!reader) throw new AppError(400, "invalid_json", "Request body is required.");
  let size = 0;
  const chunks = [];
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    size += value.length;
    if (size > 15e4) {
      await reader.cancel();
      throw new AppError(413, "request_limit", "Workout request is too large.");
    }
    chunks.push(value);
  }
  try {
    return JSON.parse(Buffer.concat(chunks).toString("utf8"));
  } catch {
    throw new AppError(400, "invalid_json", "Invalid JSON.");
  }
}
